const SETS = [
  ["কুরআন", "quran", QURAN],
  ["সিরাত", "sirah", SIRAH],
  ["ইতিহাস", "history", HISTORY],
  ["জীবন-বিধান", "life", LIFE],
  ["পরকাল", "akhirah", AKHIRAH],
];

// সঠিক উত্তরের অবস্থান deterministic(hash-ভিত্তিক) — প্রতিবার একই ফল, ইম্পোর্ট idempotent।
export function buildSeedQuestions() {
  const out = [];
  SETS.forEach(([category, key, rows], ci) => {
    rows.forEach((r, i) => {
      const [question, answer, w1, w2, w3, explanation] = r;
      const h = (Math.imul(i + 1, 2654435761) + Math.imul(ci + 7, 40503)) >>> 0;
      const pos = (h >>> 16) % 4;
      const wrong = [w1, w2, w3];
      const options = [];
      let wi = 0;
      for (let k = 0; k < 4; k++) options.push(k === pos ? answer : wrong[wi++]);
      out.push({
        id: "seed_" + key + "_" + String(i + 1).padStart(2, "0"),
        category,
        question,
        options,
        correctIndex: pos,
        explanation: explanation || null,
      });
    });
  });
  return out;
}
